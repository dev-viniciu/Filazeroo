create or replace function public.eh_funcionario(p_admin boolean default false)
returns boolean language sql stable security definer set search_path = public, auth
as $$
  select exists (
    select 1 from public.funcionarios f
    where f.auth_user_id = auth.uid() and f.ativo = true
      and (not p_admin or f.perfil = 'admin')
  );
$$;

drop policy if exists "funcionario consulta proprio perfil" on public.funcionarios;
create policy "funcionario consulta proprio perfil" on public.funcionarios
for select to authenticated using (auth_user_id = auth.uid());
drop policy if exists "funcionario consulta retiradas" on public.retiradas;
create policy "funcionario consulta retiradas" on public.retiradas
for select to authenticated using (public.eh_funcionario(false));

create or replace function public.atualizar_estoque_item(p_item text, p_quantidade integer, p_quantidade_inicial integer default null)
returns jsonb language plpgsql security definer set search_path = public, auth
as $$
declare v_item public.estoque%rowtype;
begin
  if not public.eh_funcionario(false) then raise exception 'Acesso negado: funcionário autorizado necessário.'; end if;
  if p_item is null or length(trim(p_item)) = 0 or p_quantidade is null or p_quantidade < 0 then
    raise exception 'Item e quantidade válida são obrigatórios.';
  end if;
  if p_quantidade_inicial is not null and (p_quantidade_inicial < 0 or not public.eh_funcionario(true)) then
    raise exception 'Somente administradores podem definir a quantidade inicial.';
  end if;
  select * into v_item from public.estoque where item = p_item for update;
  if not found then raise exception 'Item não encontrado no estoque.'; end if;
  update public.estoque set quantidade = p_quantidade,
    quantidade_inicial = coalesce(p_quantidade_inicial, quantidade_inicial), atualizado_em = now() where id = v_item.id
  returning * into v_item;
  return jsonb_build_object('item', v_item.item, 'quantidade', v_item.quantidade, 'quantidade_inicial', v_item.quantidade_inicial);
end;
$$;

create or replace function public.registrar_retirada(
  p_aluno_id text, p_funcionario text, p_item text default null, p_tipo text default 'primeira'
) returns jsonb language plpgsql security definer set search_path = public, auth
as $$
declare
  v_estoque public.estoque%rowtype; v_item text; v_id uuid; v_nome text;
  v_qtd_aluno integer := 0; v_total_alunos integer := 0; v_total_primeiros integer := 0;
  v_inicio_ciclo timestamptz; v_hoje date := timezone('America/Sao_Paulo', now())::date;
begin
  if not public.eh_funcionario(false) then raise exception 'Acesso negado: funcionário autorizado necessário.'; end if;
  if p_aluno_id is null or not exists (select 1 from public.alunos where id = p_aluno_id and ativo = true) then
    raise exception 'Aluno não encontrado ou inativo.';
  end if;
  if p_tipo not in ('primeira', 'repeticao') then raise exception 'Tipo de retirada inválido.'; end if;

  -- Serializa retiradas do mesmo aluno e valida a regra no banco (não apenas na interface).
  perform pg_advisory_xact_lock(hashtext(p_aluno_id)::bigint);
  select c.reiniciado_em into v_inicio_ciclo from public.configuracoes_estoque c where c.singleton = true;
  select count(*) into v_qtd_aluno from public.retiradas r
    where r.aluno_id = p_aluno_id and r.data_local = v_hoje
      and r.retirado_em >= coalesce(v_inicio_ciclo, ((v_hoje)::timestamp at time zone 'America/Sao_Paulo'));
  if p_tipo = 'primeira' and v_qtd_aluno > 0 then
    raise exception 'Este aluno já recebeu o primeiro lanche no ciclo atual.';
  end if;
  if p_tipo = 'repeticao' then
    if v_qtd_aluno = 0 then raise exception 'O primeiro lanche ainda não foi registrado.'; end if;
    if extract(hour from timezone('America/Sao_Paulo', now())) < 15 then
      raise exception 'A repetição será liberada às 15h.';
    end if;
    select count(*) into v_total_alunos from public.alunos a where a.ativo = true;
    select count(distinct r.aluno_id) into v_total_primeiros
      from public.retiradas r join public.alunos a on a.id = r.aluno_id and a.ativo = true
      where r.data_local = v_hoje
        and r.retirado_em >= coalesce(v_inicio_ciclo, ((v_hoje)::timestamp at time zone 'America/Sao_Paulo'));
    if v_total_alunos = 0 or v_total_primeiros < v_total_alunos then
      raise exception 'A repetição só é liberada depois que todos os alunos ativos receberem o primeiro lanche.';
    end if;
  end if;

  if p_item is null then
    select item into v_item from public.estoque where quantidade > 0 order by item limit 1 for update;
  else
    v_item := p_item;
  end if;
  if v_item is null then raise exception 'Sem lanche disponível.'; end if;
  select * into v_estoque from public.estoque where item = v_item for update;
  if not found or v_estoque.quantidade <= 0 then raise exception 'Sem estoque disponível para este lanche.'; end if;
  select nome into v_nome from public.funcionarios where auth_user_id = auth.uid() and ativo = true;
  update public.estoque set quantidade = quantidade - 1, atualizado_em = now() where id = v_estoque.id;
  insert into public.retiradas (aluno_id, funcionario, item, quantidade, tipo, retirado_em, data_local)
  values (p_aluno_id, coalesce(v_nome, p_funcionario, 'Funcionário'), v_item, 1, p_tipo, now(), timezone('America/Sao_Paulo', now())::date)
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'aluno_id', p_aluno_id, 'item', v_item, 'quantidade_disponivel', v_estoque.quantidade - 1);
end;
$$;

create or replace function public.listar_retiradas_hoje()
returns table (id uuid, aluno_id text, item text, quantidade integer, tipo text, retirado_em timestamptz, data_local date)
language plpgsql stable security definer set search_path = public, auth
as $$
begin
  if auth.uid() is null then raise exception 'Autenticação necessária.'; end if;
  return query select r.id, r.aluno_id, r.item, r.quantidade, r.tipo, r.retirado_em, r.data_local
    from public.retiradas r
    where r.data_local = timezone('America/Sao_Paulo', now())::date
      and r.retirado_em >= coalesce(
        (select c.reiniciado_em from public.configuracoes_estoque c where c.singleton = true),
        ((timezone('America/Sao_Paulo', now())::date)::timestamp at time zone 'America/Sao_Paulo')
      )
    order by r.retirado_em desc;
end;
$$;

create or replace function public.reiniciar_estoque_dia()
returns jsonb language plpgsql security definer set search_path = public, auth
as $$
declare v_data date := timezone('America/Sao_Paulo', now())::date; v_total integer;
begin
  if not public.eh_funcionario(true) then raise exception 'Acesso negado: somente administradores podem reiniciar o dia.'; end if;
  update public.estoque set quantidade = quantidade_inicial, data_referencia = v_data, atualizado_em = now();
  get diagnostics v_total = row_count;
  update public.configuracoes_estoque set reiniciado_em = now() where singleton = true;
  return jsonb_build_object('data_referencia', v_data, 'itens_reiniciados', v_total);
end;
$$;

